from scan_safety import http_hooks

import logging
from dataclasses import dataclass
from typing import Optional

import httpx

logger = logging.getLogger(__name__)

_SIGNATURES: list[tuple[str, str, str]] = [
    ("Cloudflare", "header:server", "cloudflare"),
    ("Cloudflare", "header:cf-ray", ""),
    ("AWS WAF", "header:x-amzn-requestid", ""),
    ("Akamai", "header:akamai-ghost-ip", ""),
    ("Sucuri", "header:x-sucuri-id", ""),
    ("Sucuri", "body", "sucuri website firewall"),
    ("Imperva Incapsula", "header:x-iinfo", ""),
    ("Imperva Incapsula", "body", "incapsula incident id"),
    ("ModSecurity", "body", "mod_security"),
    ("ModSecurity", "body", "not acceptable"),
    ("F5 BIG-IP ASM", "header:x-wa-info", ""),
    ("F5 BIG-IP ASM", "body", "the requested url was rejected"),
    ("Wordfence", "body", "generated by wordfence"),
]

_PROVOKE_PAYLOAD = "' OR '1'='1"


@dataclass
class WafDetectionResult:
    detected: bool
    name: Optional[str] = None
    raw_status: Optional[int] = None


async def detect_waf(
    url: str,
    client: Optional[httpx.AsyncClient] = None,
    timeout: float = 10.0,
    cookies: Optional[dict[str, str]] = None,
    headers: Optional[dict[str, str]] = None,
) -> WafDetectionResult:
    """Для закрытых страниц используются cookies авторизованной сессии."""
    own_client = client is None
    if own_client:
        client = httpx.AsyncClient(event_hooks=http_hooks(), timeout=timeout, follow_redirects=False, cookies=cookies, headers=headers)

    try:
        sep = "&" if "?" in url else "?"
        probe_url = f"{url}{sep}__wafcheck={_PROVOKE_PAYLOAD}"

        try:
            resp = await client.get(probe_url)
        except httpx.TransportError as e:
            logger.warning("WAF-детект: не удалось получить ответ от %s: %s", url, e)
            return WafDetectionResult(detected=False)

        body_lower = resp.text.lower()
        headers_lower = {k.lower(): v.lower() for k, v in resp.headers.items()}

        for name, where, marker in _SIGNATURES:
            if where.startswith("header:"):
                header_name = where.split(":", 1)[1]
                if header_name in headers_lower:
                    if not marker or marker in headers_lower[header_name]:
                        return WafDetectionResult(detected=True, name=name, raw_status=resp.status_code)
            elif where == "body":
                if marker in body_lower:
                    return WafDetectionResult(detected=True, name=name, raw_status=resp.status_code)

        if resp.status_code in (403, 406, 419, 429, 503):
            return WafDetectionResult(detected=True, name="unknown", raw_status=resp.status_code)

        return WafDetectionResult(detected=False, raw_status=resp.status_code)

    finally:
        if own_client:
            await client.aclose()